// Closing strip: signature, provenance and the last refresh.

import { C, PAD, W } from '../core/tokens.mjs'
import { dateIn } from '../core/format.mjs'
import { glyph } from '../core/icons.mjs'
import { constellation, glow, liveDot } from '../core/motion.mjs'
import { createDoc, h, linearGradient, txt } from '../core/svg.mjs'
import { profile } from '../content.mjs'
import { frame } from './shared/panel.mjs'

const H = 112

export default {
  name: 'footer',
  async render({ metrics }) {
    const updated = metrics.sources?.githubAt ?? metrics.generatedAt
    const doc = createDoc({
      width: W,
      height: H,
      title: `Designed and engineered by ${profile.name}`,
      desc: `Every panel on this profile is an SVG generated by scripts/profile and refreshed daily by GitHub Actions from live GitHub data${updated ? `; last update ${dateIn(updated)}` : ''}. Made in ${profile.location}.`,
    })
    const f = frame(doc, { height: H, glows: false })
    const out = [f.open]
    out.push(glow(doc, { cx: 120, cy: H, rx: 300, ry: 120, color: C.blue, opacity: 0.2 }))
    out.push(glow(doc, { cx: W - 120, cy: 0, rx: 300, ry: 110, color: C.violet, opacity: 0.16 }))
    out.push(constellation(doc, { x: 548, y: 16, w: 104, h: H - 32, nodes: 7, seed: 'footer-net', k: 2, pulses: 3, minDist: 26, edgeOpacity: 0.22 }).markup)

    const mono = linearGradient(doc, { stops: [[0, C.blue], [1, C.violet]], x1: 0, y1: 0, x2: 1, y2: 1 })
    out.push(h('rect', { x: PAD, y: 34, width: 44, height: 44, rx: 12, fill: `url(#${mono})` }))
    out.push(txt(doc, { x: PAD + 22, y: 62, text: 'JR', face: 'head', size: 18, fill: '#fff', anchor: 'middle', tracking: -0.02 }))
    out.push(txt(doc, { x: PAD + 60, y: 52, text: `Designed and engineered by ${profile.name}`, face: 'title', size: 15, fill: C.text }))
    out.push(txt(doc, { x: PAD + 60, y: 73, text: 'Every panel is an SVG built from code and regenerated by GitHub Actions.', face: 'sans', size: 12.5, fill: C.muted }))

    out.push(liveDot(doc, { cx: W - PAD - 150, cy: 47, r: 3.5, color: C.green }))
    out.push(txt(doc, { x: W - PAD - 140, y: 52, text: 'Refreshed daily', face: 'medium', size: 13, fill: C.text }))
    out.push(txt(doc, { x: W - PAD - 140, y: 72, text: updated ? `UPDATED ${dateIn(updated).toUpperCase()}` : 'UPDATED —', face: 'mono', size: 10.5, tracking: 0.06, fill: C.faint }))
    out.push(glyph('map-pin', { x: W - PAD - 156, y: 82, size: 12, color: C.faint }))
    out.push(txt(doc, { x: W - PAD - 140, y: 92, text: 'TEPIC, NAYARIT · MX', face: 'mono', size: 10.5, tracking: 0.06, fill: C.faint }))
    out.push(f.close)
    return [{ path: 'assets/generated/footer.svg', svg: await doc.render(out.join('')) }]
  },
}
