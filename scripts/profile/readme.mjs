// README.md, composed from the generated panels. Alt text comes from each SVG's <desc>, so it
// always matches the numbers the image shows.

import { esc } from './core/svg.mjs'
import { dateIn, int } from './core/format.mjs'
import { about, ai, building, highlights, profile, sections, stack, yearsOfExperience } from './content.mjs'
import { LOGIN } from './data/collect.mjs'

const BADGE = 'style=flat-square&labelColor=1e293b'

// The views counter moved from komarev.com (113 views, no label colour) to hits.sh; this seeds
// the new counter so the total carries over. hits.sh had already counted 3 preview loads.
const VIEWS_BEFORE_HITS = 110

const img = (src, alt, attrs = 'width="100%"') => `<img src="./${src}" ${attrs} alt="${esc(alt)}" />`

const panel = (src, alts, href) => {
  const tag = img(src, alts[src] ?? '')
  return `<p align="center">\n${href ? `<a href="${href}">${tag}</a>` : tag}\n</p>`
}

const section = (key) => {
  const s = sections[key]
  const alt = `${s.n} ${s.eyebrow}: ${s.lead} ${s.accent}`
  return [
    `<!-- ${s.n} · ${s.eyebrow} -->`,
    '<picture>',
    `  <source media="(prefers-color-scheme: light)" srcset="./assets/sections/${key}-light.svg" />`,
    `  ${img(`assets/sections/${key}.svg`, alt)}`,
    '</picture>',
  ].join('\n')
}

const buttons = (list) =>
  `<p align="center">\n${list.map(([file, href, alt]) => `<a href="${href}"><img src="./assets/buttons/${file}.svg" height="44" alt="${esc(alt)}" /></a>`).join('&nbsp;\n')}\n</p>`

// One line of real text under the hero: the panels are images, so this is what search engines
// and copy-paste get. Small (<sub>) so it reads as a caption, not as a second hero.
const caption = () =>
  `<p align="center"><sub><b>${profile.role}</b> at <b>${profile.company}</b> · AI-native development with AI agents, MCP, RAG and spec-driven development · ` +
  `${profile.keywords.join(', ')} · ${profile.locationFull} · ${profile.status}</sub></p>`

// Everything the panels say, as collapsible plain text (indexed even while collapsed).
function resume({ metrics, credly, now }) {
  const L = profile.links
  const c = metrics.contributions ?? {}
  const pr = metrics.pullRequests ?? {}
  const lines = [
    '<details>',
    '<summary><b>Plain-text résumé</b> · the same profile as text, for search engines, screen readers and copy-paste</summary>',
    '',
    `### ${profile.name} · ${profile.role}`,
    '',
    `${profile.locationFull} · ${profile.status} · [Email](${L.email}) · [LinkedIn](${L.linkedin}) · [Portfolio](${L.portfolio})`,
    '',
    profile.intro(yearsOfExperience(now)),
    '',
    '#### About',
    '',
    ...about.facets.map((f) => `- **${f.title}.** ${f.text}`),
    '',
    '#### AI-native engineering',
    '',
    'Spec-driven development with multi-agent workflows: a spec and a plan feed an orchestrator that fans work out to analysis, code, test and documentation agents, ' +
      'grounded by MCP servers, RAG, agent Skills and repository memory, then human review and a CI/CD release.',
    '',
    ...ai.pillars.map((p) => `- **${p.title}.** ${p.text}`),
    '',
    '#### Highlights',
    '',
    ...highlights.map((x) => `- **${x.title}** (${x.metric}). ${x.text}`),
    '',
    '#### Now building',
    '',
    `- **${building.dayJob.title}.** ${building.dayJob.text}`,
    ...building.products.map((p) => `- **${p.name}.** ${p.text}`),
    '',
    '#### Tech stack',
    '',
    ...stack.map((d) => `- **${d.domain}:** ${d.items.map((i) => i.name).join(', ')}`),
    '',
  ]
  if (credly.badges?.length) {
    lines.push('#### Credentials', '', ...credly.badges.map((b) => `- [${b.name}](${b.url}), ${b.issuer ?? 'Credly'}, ${dateIn(b.issuedAt, { month: 'short', year: 'numeric' })}`), '')
  }
  if (Number.isFinite(c.lastYear)) {
    lines.push(
      '#### GitHub, last 12 months',
      '',
      `${int(c.lastYear)} contributions on ${int(c.activeDays)} active days · ${int(pr.total)} pull requests (${Math.round((pr.mergeRate ?? 0) * 100)}% merged) · ` +
        `${int(metrics.user?.totalRepos)} repositories · longest streak ${int(c.longestStreak?.days)} days`,
      '',
    )
  }
  lines.push('</details>')
  return lines.join('\n')
}

