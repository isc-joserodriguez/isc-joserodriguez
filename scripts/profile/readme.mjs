// README.md, composed from the generated panels. Alt text comes from each SVG's <desc>, so it
// always matches the numbers the image shows.

import { esc } from './core/svg.mjs'
import { profile, sections } from './content.mjs'
import { LOGIN } from './data/collect.mjs'

const BADGE = 'style=flat-square&labelColor=1e293b'

// The views counter moved from komarev.com (113 views, no label colour) to hits.sh; this seeds
// the new counter so the total carries over. hits.sh had already counted 3 preview loads.
const VIEWS_BEFORE_HITS = 110

const img = (src, alt, attrs = 'width="100%"') => `<img src="./${src}" ${attrs} alt="${esc(alt)}" />`

const panel = (src, alts, href) => {
  const tag = img(src, alts[src] ?? '')
  return `<p align="center">\n${href ? `<a href="${href}">${tag}</a>` : tag}\n</p>`
}

const section = (key) => {
  const s = sections[key]
  const alt = `${s.n} ${s.eyebrow}: ${s.lead} ${s.accent}`
  return [
    `<!-- ${s.n} · ${s.eyebrow} -->`,
    '<picture>',
    `  <source media="(prefers-color-scheme: light)" srcset="./assets/sections/${key}-light.svg" />`,
    `  ${img(`assets/sections/${key}.svg`, alt)}`,
    '</picture>',
  ].join('\n')
}

const buttons = (list) =>
  `<p align="center">\n${list.map(([file, href, alt]) => `<a href="${href}"><img src="./assets/buttons/${file}.svg" height="44" alt="${esc(alt)}" /></a>`).join('&nbsp;\n')}\n</p>`

export function renderReadme({ alts }) {
  const L = profile.links
  const out = [
    `<!-- ${profile.name} · GitHub profile. Generated by scripts/profile/build.mjs: edit scripts/profile/content.mjs, not this file. -->`,
    '',
    panel('assets/hero.svg', alts, L.portfolio),
    '',
    buttons([
      ['email', L.email, 'Get in touch by email'],
      ['linkedin', L.linkedin, 'Connect on LinkedIn'],
      ['portfolio', L.portfolio, 'Visit my portfolio'],
    ]),
    '',
    '<p align="center">',
    `<a href="${L.github}"><img src="https://hits.sh/github.com/${LOGIN}.svg?label=profile%20views&${BADGE}&color=5593f7&extraCount=${VIEWS_BEFORE_HITS}" alt="Profile views" /></a>`,
    `<a href="${L.github}?tab=followers"><img src="https://img.shields.io/github/followers/${LOGIN}?label=followers&${BADGE}&color=a85dee&logo=github&logoColor=white" alt="GitHub followers" /></a>`,
    `<a href="${L.github}?tab=repositories"><img src="https://img.shields.io/badge/dynamic/json?url=https%3A%2F%2Fapi.github.com%2Fusers%2F${LOGIN}&query=%24.public_repos&label=public%20repos&${BADGE}&color=0891b2&logo=github&logoColor=white" alt="Public repositories" /></a>`,
    '</p>',
    '',
    '<br/>',
    '',
    section('about'),
    panel('assets/about.svg', alts),
    '',
    '<br/>',
    '',
    section('ai'),
    panel('assets/ai.svg', alts),
    '',
    '<br/>',
    '',
    section('highlights'),
    panel('assets/highlights.svg', alts),
    '',
    '<br/>',
    '',
    section('building'),
    panel('assets/building.svg', alts),
    buttons([['projects', L.projects, `See ${profile.claims.caseStudies} case studies on my portfolio`]]),
    '',
    '<br/>',
    '',
    section('activity'),
    panel('assets/generated/impact.svg', alts),
    panel('assets/generated/activity.svg', alts),
    '<p align="center">',
    '<picture>',
    '  <source media="(prefers-color-scheme: light)" srcset="./profile-3d-contrib/profile-3d-light.svg" />',
    '  <img src="./profile-3d-contrib/profile-3d-dark.svg" width="100%" alt="Isometric 3D chart of the last year of contributions, with a radar of commits, issues, pull requests, reviews and repositories." />',
    '</picture>',
    '</p>',
    '<p align="center">',
    '<picture>',
    `  <source media="(prefers-color-scheme: light)" srcset="https://raw.githubusercontent.com/${LOGIN}/${LOGIN}/output/github-snake.svg" />`,
    `  <img src="https://raw.githubusercontent.com/${LOGIN}/${LOGIN}/output/github-snake-dark.svg" width="100%" alt="A snake eating the contribution graph of the last year." />`,
    '</picture>',
    '</p>',
    '',
    '<br/>',
    '',
    section('stack'),
    panel('assets/stack.svg', alts),
    '',
    '<br/>',
    '',
    section('credentials'),
    panel('assets/generated/credentials.svg', alts, L.credly),
    buttons([
      ['credly', L.credly, 'All badges on Credly'],
      ['hackerrank', L.hackerrank, 'HackerRank profile'],
    ]),
    '',
    '<br/>',
    '',
    panel('assets/generated/footer.svg', alts, L.portfolio),
    '',
  ]
  return out.join('\n')
}
